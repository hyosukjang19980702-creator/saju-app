def _spouse_line(chart: dict) -> str:
    n = chart["spouse_count"]
    if n == 0:
        return "이성 인연을 뜻하는 별이 뚜렷하지 않아, 인연이 늦게 오거나 스스로 만들어 가는 흐름입니다."
    if n <= 2:
        return "이성 인연을 뜻하는 별이 적당해, 한 번의 인연에 집중하는 편입니다."
    return "이성 인연을 뜻하는 별이 많아 만남의 기회는 다양하지만, 선택에 신중함이 필요합니다."


def rule_report(chart: dict, cat: str, name: str = "") -> str:
    icon, label = CATEGORIES[cat]
    head, body, caution, advice = T[cat][chart["dom_group"]]
    dm = chart["day_master"]
    yl = chart["year_luck"]
    who = f"{name}님의 " if name else ""
    extra = f"\n\n{_spouse_line(chart)}" if cat == "love" else ""
    lack = chart["lacking"]
    tip = ("\n".join(f"- **{e}**: {EL_TIP[e]}" for e in lack) if lack
           else "- 오행이 고르게 분포해 특별히 부족한 기운이 없습니다.")
    return f"""### {icon} {who}{label} 전체 풀이
**{head}**

#### 1. 타고난 성향과 사주 강약
일간은 **{dm['ko']}({dm['zh']}, {dm['el']})** 입니다. {DAY_MASTER[dm['el']]}
사주의 힘은 **{chart['strength']}** 쪽입니다. {STRENGTH[chart['strength']]}

#### 2. 상세 풀이
{body}{extra}

#### 3. 올해의 흐름 ({yl['year']}년 {yl['gz_ko']}년, {yl['stem_tg']} 기운)
{YEAR[cat][yl['group']]}

#### 4. 주의할 점
{caution}

#### 5. 실천 조언
{advice}

#### 6. 오행 보완 팁 (부족한 기운)
{tip}

{DISCLAIMER}"""


